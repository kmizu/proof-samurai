package samurai.extract

/**
 * Emits clean, standalone Haskell 2010 / GHC code from an erased `ExtractedModule`.
 *
 * Design guarantees:
 * - Uses `NoImplicitPrelude` + `import qualified Prelude as P` so Proof Samurai's
 *   `Bool`, `Either`, `map`, `length`, `filter`, `reverse`, etc. never collide with Haskell's `Prelude`.
 * - Qualifies data constructors as `TypeName_CtorName` (`Nat_Zero`, `List_Cons`, `Vec_Cons`, `Subset_Mk`)
 *   so constructors from multiple ADTs (e.g. `List.Nil` vs `Vec.Nil`, `Pair.Mk` vs `Subset.Mk`) never clash.
 * - Emits `deriving (P.Eq, P.Show)` automatically for first-order ADTs and omits it for higher-order ADTs.
 * - Normalizes type variables to lowercase (`Element` -> `element`) and escapes Haskell reserved keywords.
 */
object HaskellEmitter {

  private val HaskellReserved: Set[String] = Set(
    "as", "case", "class", "data", "default", "deriving", "do", "else",
    "forall", "foreign", "hiding", "if", "import", "in", "infix", "infixl",
    "infixr", "instance", "let", "mdo", "module", "newtype", "of", "proc",
    "qualified", "rec", "then", "type", "where"
  )

  private def sanitizeRaw(name: String): String =
    name.map(c => if (c.isLetterOrDigit || c == '_' || c == '\'') c else '_')

  private def hsTypeName(name: String): String = {
    val clean = sanitizeRaw(name)
    if (clean.isEmpty) "T"
    else if (clean.head.isUpper) clean
    else if (clean.head.isLower) clean.head.toUpper.toString + clean.tail
    else s"T_$clean"
  }

  private def hsModuleName(name: String): String = {
    val parts = name.split('.').toList.filter(_.nonEmpty).map(hsTypeName)
    if (parts.isEmpty) "ExtractedSamurai" else parts.mkString(".")
  }

  private def hsCtorName(indName: String, ctorName: String): String =
    s"${hsTypeName(indName)}_${hsTypeName(ctorName)}"

  private def hsTypeVar(name: String): String = {
    val clean = sanitizeRaw(name).replace('\'', '_')
    val lowered =
      if (clean.isEmpty) "a"
      else if (clean.head.isUpper) clean.head.toLower.toString + clean.tail
      else if (clean.head.isLower) clean
      else s"t$clean"
    if (HaskellReserved.contains(lowered)) s"${lowered}_" else lowered
  }

  private def hsValIdent(name: String): String = {
    if (name == "_") return "_"
    val clean = sanitizeRaw(name)
    val base =
      if (clean.isEmpty) "_v"
      else if (clean.head.isUpper) s"v_$clean"
      else clean
    if (HaskellReserved.contains(base)) s"${base}_" else base
  }

  private def escapeString(raw: String): String =
    raw
      .replace("\\", "\\\\")
      .replace("\"", "\\\"")
      .replace("\n", "\\n")
      .replace("\r", "\\r")

  def emit(module: ExtractedModule): String = {
    val sb = new StringBuilder
    sb.append("-- ==========================================================================\n")
    sb.append("-- Generated by Proof Samurai Code Extraction (Target: Haskell)\n")
    sb.append(s"-- Verified theorems (erased): ${module.manifest.verifiedTheorems.size}\n")
    sb.append(s"-- Erased propositions:        ${module.manifest.erasedPropositions.size}\n")
    sb.append(s"-- Axiom-free verification:    ${module.manifest.isAxiomFree}\n")
    if (!module.manifest.isAxiomFree) {
      sb.append(s"-- WARNING - Axioms used:      ${module.manifest.axiomsUsed.toList.sorted.mkString(", ")}\n")
    }
    if (module.manifest.partialFunctions.nonEmpty) {
      sb.append(s"-- Partial functions:          ${module.manifest.partialFunctions.mkString(", ")}\n")
    }
    sb.append("-- ==========================================================================\n\n")

    sb.append("{-# LANGUAGE NoImplicitPrelude #-}\n")
    sb.append(s"module ${hsModuleName(module.moduleName)} where\n\n")
    sb.append("import qualified Prelude as P\n\n")

    val derivableTypes = computeDerivableTypes(module.dataDecls)

    for (data <- module.dataDecls) {
      emitDataDecl(sb, data, derivableTypes.contains(data.name))
      sb.append("\n")
    }

    for (fn <- module.defDecls) {
      emitDefDecl(sb, fn)
      sb.append("\n")
    }

    sb.toString
  }

  private def computeDerivableTypes(dataDecls: List[ExtractedDataDecl]): Set[String] = {
    var derivable = dataDecls.map(_.name).toSet
    var changed = true

    def typeIsDerivable(ty: ExtractedType): Boolean = ty match {
      case ExtractedType.TUnit          => true
      case ExtractedType.TVar(_)        => true
      case ExtractedType.TFun(_, _)     => false
      case ExtractedType.TAny           => false
      case ExtractedType.TInd(n, args)  => derivable.contains(n) && args.forall(typeIsDerivable)
    }

    while (changed) {
      changed = false
      for (d <- dataDecls if derivable.contains(d.name)) {
        val ok = d.constructors.forall(c => c.fields.forall { case (_, fTy) => typeIsDerivable(fTy) })
        if (!ok) {
          derivable -= d.name
          changed = true
        }
      }
    }
    derivable
  }

  private def containsAny(ty: ExtractedType): Boolean = ty match {
    case ExtractedType.TAny          => true
    case ExtractedType.TUnit         => false
    case ExtractedType.TVar(_)       => false
    case ExtractedType.TInd(_, args) => args.exists(containsAny)
    case ExtractedType.TFun(d, c)    => containsAny(d) || containsAny(c)
  }

  private def emitDataDecl(sb: StringBuilder, data: ExtractedDataDecl, canDerive: Boolean): Unit = {
    val tParams =
      if (data.typeParams.isEmpty) ""
      else " " + data.typeParams.map(hsTypeVar).mkString(" ")
    sb.append(s"data ${hsTypeName(data.name)}$tParams\n")
    if (data.constructors.isEmpty) {
      // Empty data type (valid in GHC with EmptyDataDecls or standard Haskell)
      ()
    } else {
      for ((ctor, idx) <- data.constructors.zipWithIndex) {
        val sep = if (idx == 0) "  = " else "  | "
        val fieldsStr =
          if (ctor.fields.isEmpty) ""
          else " " + ctor.fields.map { case (_, fTy) => emitTypeAtom(fTy) }.mkString(" ")
        sb.append(s"$sep${hsCtorName(data.name, ctor.name)}$fieldsStr\n")
      }
      if (canDerive) {
        sb.append("  deriving (P.Eq, P.Show)\n")
      }
    }
  }

  private def emitDefDecl(sb: StringBuilder, fn: ExtractedDefDecl): Unit = {
    val fnIdent = hsValIdent(fn.name)
    val hasAny = fn.valueParams.exists { case (_, t) => containsAny(t) } || containsAny(fn.returnType)

    if (!hasAny) {
      val fullTy = fn.valueParams.foldRight(fn.returnType) { case ((_, pTy), acc) =>
        ExtractedType.TFun(pTy, acc)
      }
      sb.append(s"$fnIdent :: ${emitType(fullTy)}\n")
    }

    val paramsStr =
      if (fn.valueParams.isEmpty) ""
      else " " + fn.valueParams.map { case (n, _) => hsValIdent(n) }.mkString(" ")
    sb.append(s"$fnIdent$paramsStr =\n")
    sb.append("  ")
    sb.append(emitExpr(fn.body, indent = 2))
    sb.append("\n")
  }

  private def emitType(ty: ExtractedType): String = ty match {
    case ExtractedType.TUnit          => "()"
    case ExtractedType.TVar(name)     => hsTypeVar(name)
    case ExtractedType.TAny           => "()"
    case ExtractedType.TInd(name, Nil) => hsTypeName(name)
    case ExtractedType.TInd(name, args) =>
      s"${hsTypeName(name)} ${args.map(emitTypeAtom).mkString(" ")}"
    case ExtractedType.TFun(dom, cod) =>
      val domStr = dom match {
        case ExtractedType.TFun(_, _) => s"(${emitType(dom)})"
        case _                        => emitType(dom)
      }
      s"$domStr -> ${emitType(cod)}"
  }

  private def emitTypeAtom(ty: ExtractedType): String = ty match {
    case ExtractedType.TUnit          => "()"
    case ExtractedType.TVar(name)     => hsTypeVar(name)
    case ExtractedType.TAny           => "()"
    case ExtractedType.TInd(name, Nil) => hsTypeName(name)
    case other                        => s"(${emitType(other)})"
  }

  private def isAtomicExpr(expr: ExtractedExpr): Boolean = expr match {
    case ExtractedExpr.EUnit               => true
    case ExtractedExpr.EVar(_)             => true
    case ExtractedExpr.EConst(_, _)        => true
    case ExtractedExpr.ECtor(_, _, _, Nil) => true
    case ExtractedExpr.ELam(_, _, _)       => true
    case ExtractedExpr.ELet(_, _, _)       => true
    case _                                 => false
  }

  private def collectApps(expr: ExtractedExpr): (ExtractedExpr, List[ExtractedExpr]) = {
    def loop(cur: ExtractedExpr, acc: List[ExtractedExpr]): (ExtractedExpr, List[ExtractedExpr]) = cur match {
      case ExtractedExpr.EApp(fn, arg) => loop(fn, arg :: acc)
      case other                       => (other, acc)
    }
    loop(expr, Nil)
  }

  private def emitAtom(expr: ExtractedExpr, indent: Int): String =
    if (isAtomicExpr(expr)) emitExpr(expr, indent)
    else s"(${emitExpr(expr, indent + 1)})"

  private def emitExpr(expr: ExtractedExpr, indent: Int): String = {
    val pad = " " * indent
    expr match {
      case ExtractedExpr.EUnit =>
        "()"

      case ExtractedExpr.EUnreachable(reason) =>
        s"""P.error "Proof Samurai unreachable: ${escapeString(reason)}""""

      case ExtractedExpr.EVar(name) =>
        hsValIdent(name)

      case ExtractedExpr.EConst(name, _) =>
        hsValIdent(name)

      case ExtractedExpr.ECtor(indName, ctorName, _, args) =>
        val ctor = hsCtorName(indName, ctorName)
        if (args.isEmpty) ctor
        else s"$ctor ${args.map(emitAtom(_, indent)).mkString(" ")}"

      case ExtractedExpr.ELam(paramName, _, body) =>
        s"(\\${hsValIdent(paramName)} -> ${emitExpr(body, indent + 2)})"

      case app @ ExtractedExpr.EApp(_, _) =>
        val (head, args) = collectApps(app)
        val headStr = emitAtom(head, indent)
        val argsStr = args.map(emitAtom(_, indent)).mkString(" ")
        s"$headStr $argsStr"

      case ExtractedExpr.ELet(name, value, body) =>
        val vStr = emitExpr(value, indent + 4)
        val bStr = emitExpr(body, indent + 3)
        s"(let\n$pad  ${hsValIdent(name)} =\n$pad    $vStr\n$pad in\n$pad   $bStr)"

      case ExtractedExpr.EMatch(indName, scrutinee, branches) =>
        if (branches.isEmpty) {
          """P.error "Proof Samurai unreachable: empty match""""
        } else {
          val sStr = emitExpr(scrutinee, indent + 2)
          val sb = new StringBuilder
          sb.append(s"case $sStr of\n")
          for ((ctorName, fieldNames, body) <- branches) {
            val ctor = hsCtorName(indName, ctorName)
            val pat =
              if (fieldNames.isEmpty) ctor
              else s"$ctor ${fieldNames.map(hsValIdent).mkString(" ")}"
            val bStr = emitExpr(body, indent + 4)
            sb.append(s"$pad  $pat ->\n$pad    $bStr\n")
          }
          sb.toString.stripSuffix("\n")
        }
    }
  }
}
