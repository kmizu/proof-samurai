package samurai.extract

import scala.collection.mutable

/**
 * Emits clean, standalone OCaml (4.x / 5.x) code from an erased `ExtractedModule`.
 *
 * Design guarantees:
 * - Qualifies variant constructors as `TypeName_CtorName` (`Nat_Zero`, `List_Cons`, `Vec_Cons`, `Subset_Mk`)
 *   to avoid constructor ambiguity / shadowing across ADTs.
 * - Uses Tarjan strongly connected components (SCCs) on both `dataDecls` and `defDecls` to emit
 *   topologically ordered `type ... and ...` and `let` / `let rec ... and ...` blocks automatically
 *   (handling mutual recursion such as `isEven` / `isOdd` natively).
 * - Protects zero-argument polymorphic or effectful/unreachable definitions (such as `absurd`)
 *   from eager module-load evaluation and the OCaml value restriction by thunking them over `Stdlib.unit`.
 * - Wraps nested `match`, `let`, and `fun` expressions safely and escapes all OCaml reserved keywords.
 */
object OCamlEmitter {

  private val OCamlReserved: Set[String] = Set(
    "and", "as", "assert", "asr", "begin", "class", "constraint", "do", "done",
    "downto", "else", "end", "exception", "external", "false", "for", "fun",
    "function", "functor", "if", "in", "include", "inherit", "initializer",
    "land", "lazy", "let", "lor", "lsl", "lsr", "lxor", "match", "method",
    "mod", "module", "mutable", "new", "nonrec", "object", "of", "open", "or",
    "private", "rec", "sig", "struct", "then", "to", "true", "try", "type",
    "val", "virtual", "when", "while", "with"
  )

  private def sanitizeRaw(name: String): String =
    name.map(c => if (c.isLetterOrDigit || c == '_' || c == '\'') c else '_')

  private def mlCtorSegment(name: String): String = {
    val clean = sanitizeRaw(name).replace('\'', '_')
    if (clean.isEmpty) "C"
    else if (clean.head.isUpper) clean
    else if (clean.head.isLower) clean.head.toUpper.toString + clean.tail
    else s"C_$clean"
  }

  private def mlCtorName(indName: String, ctorName: String): String =
    s"${mlCtorSegment(indName)}_${mlCtorSegment(ctorName)}"

  private def mlTypeName(name: String): String = {
    val clean = sanitizeRaw(name).replace('\'', '_')
    val lowered =
      if (clean.isEmpty) "t"
      else if (clean.head.isUpper) clean.head.toLower.toString + clean.tail
      else if (clean.head.isLower) clean
      else s"t_$clean"
    if (OCamlReserved.contains(lowered)) s"${lowered}_" else lowered
  }

  private def mlTypeVar(name: String): String = {
    val clean = sanitizeRaw(name).replace('\'', '_')
    val lowered =
      if (clean.isEmpty) "a"
      else if (clean.head.isUpper) clean.head.toLower.toString + clean.tail
      else if (clean.head.isLower) clean
      else s"t$clean"
    val safe = if (OCamlReserved.contains(lowered)) s"${lowered}_" else lowered
    s"'$safe"
  }

  private def mlValIdent(name: String): String = {
    if (name == "_") return "_"
    val clean = sanitizeRaw(name)
    val base =
      if (clean.isEmpty) "_v"
      else if (clean.head.isUpper) s"v_$clean"
      else clean
    if (OCamlReserved.contains(base)) s"${base}_" else base
  }

  private def escapeString(raw: String): String =
    raw
      .replace("\\", "\\\\")
      .replace("\"", "\\\"")
      .replace("\n", "\\n")
      .replace("\r", "\\r")

  def emit(module: ExtractedModule): String = {
    val sb = new StringBuilder
    sb.append("(* ========================================================================== *)\n")
    sb.append(s"(* Generated by Proof Samurai Code Extraction (Target: OCaml, Module: ${module.moduleName}) *)\n")
    sb.append(s"(* Verified theorems (erased): ${module.manifest.verifiedTheorems.size} *)\n")
    sb.append(s"(* Erased propositions:        ${module.manifest.erasedPropositions.size} *)\n")
    sb.append(s"(* Axiom-free verification:    ${module.manifest.isAxiomFree} *)\n")
    if (!module.manifest.isAxiomFree) {
      sb.append(s"(* WARNING - Axioms used:      ${module.manifest.axiomsUsed.toList.sorted.mkString(", ")} *)\n")
    }
    if (module.manifest.partialFunctions.nonEmpty) {
      sb.append(s"(* Partial functions:          ${module.manifest.partialFunctions.mkString(", ")} *)\n")
    }
    sb.append("(* ========================================================================== *)\n\n")

    // Emit algebraic data types in topological SCC order (grouping mutual types with `type ... and ...`)
    val dataSccs = computeDataSccs(module.dataDecls)
    for (scc <- dataSccs) {
      emitDataScc(sb, scc)
      sb.append("\n")
    }

    // Identify 0-arg defs that must be thunked over `Stdlib.unit` (e.g. `absurd`, polymorphic or non-value 0-arg defs)
    val defMap = module.defDecls.map(d => d.name -> d).toMap
    val defRefs = module.defDecls.map(d => d.name -> collectDefRefs(d.body, defMap.keySet, d.valueParams.map(_._1).toSet)).toMap
    val defSccs = computeDefSccs(module.defDecls, defRefs)

    val recursiveNames: Set[String] = defSccs.flatMap { scc =>
      if (scc.length > 1) scc.map(_.name)
      else if (scc.length == 1 && defRefs(scc.head.name).contains(scc.head.name)) List(scc.head.name)
      else Nil
    }.toSet

    val thunkedDefs: Set[String] = module.defDecls.collect {
      case d if d.valueParams.isEmpty && (d.typeParams.nonEmpty || recursiveNames.contains(d.name) || !isSyntacticValue(d.body)) =>
        d.name
    }.toSet

    for (scc <- defSccs) {
      val isRec = scc.length > 1 || (scc.length == 1 && defRefs(scc.head.name).contains(scc.head.name))
      emitDefScc(sb, scc, isRec, thunkedDefs)
      sb.append("\n")
    }

    sb.toString
  }

  private def isSyntacticValue(expr: ExtractedExpr): Boolean = expr match {
    case ExtractedExpr.EUnit              => true
    case ExtractedExpr.EVar(_)            => true
    case ExtractedExpr.ELam(_, _, _)      => true
    case ExtractedExpr.ECtor(_, _, _, as) => as.forall(isSyntacticValue)
    case _                                => false
  }

  private def collectTypeRefs(ty: ExtractedType, known: Set[String]): Set[String] = ty match {
    case ExtractedType.TUnit | ExtractedType.TVar(_) | ExtractedType.TAny => Set.empty
    case ExtractedType.TFun(d, c) => collectTypeRefs(d, known) ++ collectTypeRefs(c, known)
    case ExtractedType.TInd(name, args) =>
      val base = if (known.contains(name)) Set(name) else Set.empty[String]
      args.foldLeft(base)((acc, a) => acc ++ collectTypeRefs(a, known))
  }

  private def collectDefRefs(expr: ExtractedExpr, known: Set[String], shadowed: Set[String]): Set[String] = expr match {
    case ExtractedExpr.EUnit | ExtractedExpr.EUnreachable(_) => Set.empty
    case ExtractedExpr.EVar(name) =>
      if (!shadowed.contains(name) && known.contains(name)) Set(name) else Set.empty
    case ExtractedExpr.EConst(name, _) =>
      if (known.contains(name)) Set(name) else Set.empty
    case ExtractedExpr.ECtor(_, _, _, args) =>
      args.foldLeft(Set.empty[String])((acc, a) => acc ++ collectDefRefs(a, known, shadowed))
    case ExtractedExpr.ELam(p, _, body) =>
      collectDefRefs(body, known, shadowed + p)
    case ExtractedExpr.EApp(c, a) =>
      collectDefRefs(c, known, shadowed) ++ collectDefRefs(a, known, shadowed)
    case ExtractedExpr.ELet(n, v, b) =>
      collectDefRefs(v, known, shadowed) ++ collectDefRefs(b, known, shadowed + n)
    case ExtractedExpr.EMatch(_, scrut, branches) =>
      val base = collectDefRefs(scrut, known, shadowed)
      branches.foldLeft(base) { case (acc, (_, fields, body)) =>
        acc ++ collectDefRefs(body, known, shadowed ++ fields.filterNot(_ == "_"))
      }
  }

  private def tarjanSccs[A](items: List[A], keyOf: A => String, depsOf: A => Set[String]): List[List[A]] = {
    val indexByKey = items.zipWithIndex.map { case (a, i) => keyOf(a) -> i }.toMap
    val itemByKey = items.map(a => keyOf(a) -> a).toMap

    var nextIndex = 0
    val indices = mutable.Map.empty[String, Int]
    val lowlink = mutable.Map.empty[String, Int]
    val onStack = mutable.Set.empty[String]
    val stack = mutable.Stack.empty[String]
    val sccs = List.newBuilder[List[A]]

    def strongConnect(v: String): Unit = {
      indices(v) = nextIndex
      lowlink(v) = nextIndex
      nextIndex += 1
      stack.push(v)
      onStack += v

      val neighbors = depsOf(itemByKey(v)).toList.filter(itemByKey.contains).sortBy(indexByKey)
      for (w <- neighbors) {
        if (!indices.contains(w)) {
          strongConnect(w)
          lowlink(v) = math.min(lowlink(v), lowlink(w))
        } else if (onStack.contains(w)) {
          lowlink(v) = math.min(lowlink(v), indices(w))
        }
      }

      if (lowlink(v) == indices(v)) {
        val comp = List.newBuilder[A]
        var done = false
        while (!done) {
          val w = stack.pop()
          onStack -= w
          comp += itemByKey(w)
          if (w == v) done = true
        }
        sccs += comp.result().sortBy(a => indexByKey(keyOf(a)))
      }
    }

    for (item <- items) {
      val k = keyOf(item)
      if (!indices.contains(k)) strongConnect(k)
    }

    sccs.result()
  }

  private def computeDataSccs(dataDecls: List[ExtractedDataDecl]): List[List[ExtractedDataDecl]] = {
    val known = dataDecls.map(_.name).toSet
    tarjanSccs[ExtractedDataDecl](
      dataDecls,
      _.name,
      d => d.constructors.flatMap(_.fields).foldLeft(Set.empty[String]) { case (acc, (_, fTy)) =>
        acc ++ collectTypeRefs(fTy, known)
      }
    )
  }

  private def computeDefSccs(
    defDecls: List[ExtractedDefDecl],
    defRefs: Map[String, Set[String]]
  ): List[List[ExtractedDefDecl]] =
    tarjanSccs[ExtractedDefDecl](defDecls, _.name, d => defRefs.getOrElse(d.name, Set.empty))

  private def containsAny(ty: ExtractedType): Boolean = ty match {
    case ExtractedType.TAny          => true
    case ExtractedType.TUnit         => false
    case ExtractedType.TVar(_)       => false
    case ExtractedType.TInd(_, args) => args.exists(containsAny)
    case ExtractedType.TFun(d, c)    => containsAny(d) || containsAny(c)
  }

  private def emitDataScc(sb: StringBuilder, scc: List[ExtractedDataDecl]): Unit = {
    for ((data, idx) <- scc.zipWithIndex) {
      val kw = if (idx == 0) "type" else "and"
      val tParams = data.typeParams match {
        case Nil       => ""
        case List(one) => s"${mlTypeVar(one)} "
        case many      => s"(${many.map(mlTypeVar).mkString(", ")}) "
      }
      if (data.constructors.isEmpty) {
        sb.append(s"$kw $tParams${mlTypeName(data.name)} = |\n")
      } else {
        sb.append(s"$kw $tParams${mlTypeName(data.name)} =\n")
        for (ctor <- data.constructors) {
          val ctorName = mlCtorName(data.name, ctor.name)
          if (ctor.fields.isEmpty) {
            sb.append(s"  | $ctorName\n")
          } else {
            val fieldsStr = ctor.fields.map { case (_, fTy) => emitCtorFieldType(fTy) }.mkString(" * ")
            sb.append(s"  | $ctorName of $fieldsStr\n")
          }
        }
      }
    }
  }

  private def emitDefScc(
    sb: StringBuilder,
    scc: List[ExtractedDefDecl],
    isRec: Boolean,
    thunkedDefs: Set[String]
  ): Unit = {
    for ((fn, idx) <- scc.zipWithIndex) {
      val kw =
        if (idx == 0) { if (isRec) "let rec" else "let" }
        else "and"
      val fnIdent = mlValIdent(fn.name)
      val paramsStr =
        if (thunkedDefs.contains(fn.name)) {
          " (() : Stdlib.unit)"
        } else if (fn.valueParams.isEmpty) {
          ""
        } else {
          " " + fn.valueParams
            .map { case (pName, pTy) =>
              if (containsAny(pTy)) mlValIdent(pName)
              else s"(${mlValIdent(pName)} : ${emitType(pTy)})"
            }
            .mkString(" ")
        }
      val retAnn =
        if (containsAny(fn.returnType)) ""
        else s" : ${emitType(fn.returnType)}"
      sb.append(s"$kw $fnIdent$paramsStr$retAnn =\n")
      sb.append("  ")
      sb.append(emitExpr(fn.body, thunkedDefs, indent = 2))
      sb.append("\n")
    }
  }

  private def emitType(ty: ExtractedType): String = ty match {
    case ExtractedType.TUnit          => "Stdlib.unit"
    case ExtractedType.TVar(name)     => mlTypeVar(name)
    case ExtractedType.TAny           => "Obj.t"
    case ExtractedType.TInd(name, Nil) => mlTypeName(name)
    case ExtractedType.TInd(name, List(single)) =>
      s"${emitTypeArg(single)} ${mlTypeName(name)}"
    case ExtractedType.TInd(name, many) =>
      s"(${many.map(emitType).mkString(", ")}) ${mlTypeName(name)}"
    case ExtractedType.TFun(dom, cod) =>
      val domStr = dom match {
        case ExtractedType.TFun(_, _) => s"(${emitType(dom)})"
        case _                        => emitType(dom)
      }
      s"$domStr -> ${emitType(cod)}"
  }

  private def emitTypeArg(ty: ExtractedType): String = ty match {
    case ExtractedType.TUnit          => "Stdlib.unit"
    case ExtractedType.TVar(name)     => mlTypeVar(name)
    case ExtractedType.TAny           => "Obj.t"
    case ExtractedType.TInd(name, Nil) => mlTypeName(name)
    case other                        => s"(${emitType(other)})"
  }

  private def emitCtorFieldType(ty: ExtractedType): String = ty match {
    case ExtractedType.TFun(_, _) => s"(${emitType(ty)})"
    case _                        => emitType(ty)
  }

  private def isAtomicExpr(expr: ExtractedExpr, thunkedDefs: Set[String]): Boolean = expr match {
    case ExtractedExpr.EUnit               => true
    case ExtractedExpr.EVar(_)             => true
    case ExtractedExpr.EConst(_, _)        => true
    case ExtractedExpr.ECtor(_, _, _, Nil) => true
    case ExtractedExpr.ELam(_, _, _)       => true
    case ExtractedExpr.ELet(_, _, _)       => true
    case ExtractedExpr.EMatch(_, _, _)     => true
    case _                                 => false
  }

  private def collectApps(expr: ExtractedExpr): (ExtractedExpr, List[ExtractedExpr]) = {
    def loop(cur: ExtractedExpr, acc: List[ExtractedExpr]): (ExtractedExpr, List[ExtractedExpr]) = cur match {
      case ExtractedExpr.EApp(fn, arg) => loop(fn, arg :: acc)
      case other                       => (other, acc)
    }
    loop(expr, Nil)
  }

  private def emitAtom(expr: ExtractedExpr, thunkedDefs: Set[String], indent: Int): String =
    if (isAtomicExpr(expr, thunkedDefs)) emitExpr(expr, thunkedDefs, indent)
    else s"(${emitExpr(expr, thunkedDefs, indent + 1)})"

  private def emitExpr(expr: ExtractedExpr, thunkedDefs: Set[String], indent: Int): String = {
    val pad = " " * indent
    expr match {
      case ExtractedExpr.EUnit =>
        "()"

      case ExtractedExpr.EUnreachable(reason) =>
        s"""failwith "Proof Samurai unreachable: ${escapeString(reason)}""""

      case ExtractedExpr.EVar(name) =>
        mlValIdent(name)

      case ExtractedExpr.EConst(name, _) =>
        if (thunkedDefs.contains(name)) s"(${mlValIdent(name)} ())"
        else mlValIdent(name)

      case ExtractedExpr.ECtor(indName, ctorName, _, args) =>
        val ctor = mlCtorName(indName, ctorName)
        args match {
          case Nil       => ctor
          case List(one) => s"$ctor ${emitAtom(one, thunkedDefs, indent)}"
          case many      => s"$ctor (${many.map(emitExpr(_, thunkedDefs, indent)).mkString(", ")})"
        }

      case ExtractedExpr.ELam(paramName, paramType, body) =>
        val pStr =
          if (containsAny(paramType)) mlValIdent(paramName)
          else s"(${mlValIdent(paramName)} : ${emitType(paramType)})"
        s"(fun $pStr -> ${emitExpr(body, thunkedDefs, indent + 2)})"

      case app @ ExtractedExpr.EApp(_, _) =>
        val (head, args) = collectApps(app)
        val headStr = emitAtom(head, thunkedDefs, indent)
        val argsStr = args.map(emitAtom(_, thunkedDefs, indent)).mkString(" ")
        s"$headStr $argsStr"

      case ExtractedExpr.ELet(name, value, body) =>
        val vStr = emitExpr(value, thunkedDefs, indent + 2)
        val bStr = emitExpr(body, thunkedDefs, indent + 2)
        s"(let ${mlValIdent(name)} =\n$pad  $vStr\n${pad}in\n$pad  $bStr)"

      case ExtractedExpr.EMatch(indName, scrutinee, branches) =>
        if (branches.isEmpty) {
          """failwith "Proof Samurai unreachable: empty match""""
        } else {
          val sStr = emitExpr(scrutinee, thunkedDefs, indent + 2)
          val sb = new StringBuilder
          sb.append(s"(match $sStr with\n")
          for ((ctorName, fieldNames, body) <- branches) {
            val ctor = mlCtorName(indName, ctorName)
            val pat = fieldNames match {
              case Nil       => ctor
              case List(one) => s"$ctor ${mlValIdent(one)}"
              case many      => s"$ctor (${many.map(mlValIdent).mkString(", ")})"
            }
            val bStr = emitExpr(body, thunkedDefs, indent + 4)
            sb.append(s"$pad| $pat ->\n$pad    $bStr\n")
          }
          sb.toString.stripSuffix("\n") + ")"
        }
    }
  }
}
