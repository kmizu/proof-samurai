package samurai.extract

/**
 * Emits clean, standalone, idiomatic Scala 3 code (strictly brace-delimited, no indent syntax)
 * from an erased `ExtractedModule`.
 */
object Scala3Emitter {

  private val ScalaReserved: Set[String] = Set(
    "abstract", "case", "catch", "class", "def", "do", "else", "enum", "export",
    "extends", "false", "final", "finally", "for", "given", "if", "implicit",
    "import", "lazy", "match", "new", "null", "object", "override", "package",
    "private", "protected", "return", "sealed", "super", "then", "this", "throw",
    "trait", "true", "try", "type", "val", "var", "while", "with", "yield"
  )

  private def safeIdent(name: String): String =
    if (name == "_") "_"
    else if (ScalaReserved.contains(name)) s"`$name`"
    else name.replace('\'', '_')

  def emit(module: ExtractedModule, packageName: Option[String] = None): String = {
    val sb = new StringBuilder
    sb.append("// ==========================================================================\n")
    sb.append("// Generated by Proof Samurai Code Extraction (Target: Scala 3, brace syntax)\n")
    sb.append(s"// Verified theorems (erased): ${module.manifest.verifiedTheorems.size}\n")
    sb.append(s"// Erased propositions:        ${module.manifest.erasedPropositions.size}\n")
    sb.append(s"// Axiom-free verification:    ${module.manifest.isAxiomFree}\n")
    if (!module.manifest.isAxiomFree) {
      sb.append(s"// WARNING - Axioms used:      ${module.manifest.axiomsUsed.toList.sorted.mkString(", ")}\n")
    }
    sb.append("// ==========================================================================\n\n")

    packageName.foreach { pkg =>
      sb.append(s"package $pkg\n\n")
    }

    sb.append(s"object ${safeIdent(module.moduleName)} {\n")

    // Emit algebraic data types
    for (data <- module.dataDecls) {
      emitDataDecl(sb, data)
      sb.append("\n")
    }

    // Build arity map for multi-arg direct calls and track generic enums for nullary ctor syntax
    val defArities: Map[String, Int] = module.defDecls.map(d => d.name -> d.valueParams.length).toMap
    val recordNames: Set[String] = module.dataDecls.filter(_.isRecord).map(_.name).toSet
    val genericEnumNames: Set[String] = module.dataDecls.filter(d => !d.isRecord && d.typeParams.nonEmpty).map(_.name).toSet

    // Emit verified functions
    for (fn <- module.defDecls) {
      emitDefDecl(sb, fn, defArities, recordNames, genericEnumNames)
      sb.append("\n")
    }

    sb.append("}\n")
    sb.toString
  }

  private def emitDataDecl(sb: StringBuilder, data: ExtractedDataDecl): Unit = {
    val tParams =
      if (data.typeParams.isEmpty) ""
      else s"[${data.typeParams.map(safeIdent).mkString(", ")}]"

    if (data.isRecord && data.constructors.length == 1) {
      val fields = data.constructors.head.fields
        .map { case (fName, fTy) => s"${safeIdent(fName)}: ${emitType(fTy)}" }
        .mkString(", ")
      sb.append(s"  final case class ${safeIdent(data.name)}$tParams($fields)\n")
    } else {
      sb.append(s"  enum ${safeIdent(data.name)}$tParams {\n")
      for (ctor <- data.constructors) {
        if (ctor.fields.isEmpty) {
          val ext =
            if (data.typeParams.isEmpty) ""
            else s" extends ${safeIdent(data.name)}[${data.typeParams.map(_ => "Nothing").mkString(", ")}]"
          // Keep invariant/covariant clean by using case with explicit params or standard Scala 3 enum case
          val _ = ext
          if (data.typeParams.isEmpty) {
            sb.append(s"    case ${safeIdent(ctor.name)}\n")
          } else {
            sb.append(s"    case ${safeIdent(ctor.name)}() extends ${safeIdent(data.name)}$tParams\n")
          }
        } else {
          val fields = ctor.fields
            .map { case (fName, fTy) => s"${safeIdent(fName)}: ${emitType(fTy)}" }
            .mkString(", ")
          sb.append(s"    case ${safeIdent(ctor.name)}($fields)\n")
        }
      }
      sb.append("  }\n")
    }
  }

  private def emitDefDecl(
    sb: StringBuilder,
    fn: ExtractedDefDecl,
    defArities: Map[String, Int],
    recordNames: Set[String],
    genericEnumNames: Set[String]
  ): Unit = {
    val tParams =
      if (fn.typeParams.isEmpty) ""
      else s"[${fn.typeParams.map(safeIdent).mkString(", ")}]"
    val vParams =
      if (fn.valueParams.isEmpty) ""
      else "(" + fn.valueParams.map { case (n, t) => s"${safeIdent(n)}: ${emitType(t)}" }.mkString(", ") + ")"
    val retTy = emitType(fn.returnType)

    sb.append(s"  def ${safeIdent(fn.name)}$tParams$vParams: $retTy = {\n")
    sb.append("    ")
    sb.append(emitExpr(fn.body, defArities, recordNames, genericEnumNames, indent = 4))
    sb.append("\n  }\n")
  }

  private def emitType(ty: ExtractedType): String = ty match {
    case ExtractedType.TUnit => "scala.Unit"
    case ExtractedType.TVar(name) => safeIdent(name)
    case ExtractedType.TAny => "Any"
    case ExtractedType.TInd(name, Nil) => safeIdent(name)
    case ExtractedType.TInd(name, args) => s"${safeIdent(name)}[${args.map(emitType).mkString(", ")}]"
    case ExtractedType.TFun(dom, cod) => s"(${emitType(dom)} => ${emitType(cod)})"
  }

  private def collectApps(expr: ExtractedExpr): (ExtractedExpr, List[ExtractedExpr]) = {
    def loop(cur: ExtractedExpr, acc: List[ExtractedExpr]): (ExtractedExpr, List[ExtractedExpr]) = cur match {
      case ExtractedExpr.EApp(fn, arg) => loop(fn, arg :: acc)
      case other                       => (other, acc)
    }
    loop(expr, Nil)
  }

  private def emitExpr(
    expr: ExtractedExpr,
    defArities: Map[String, Int],
    recordNames: Set[String],
    genericEnumNames: Set[String],
    indent: Int
  ): String = {
    val pad = " " * indent
    expr match {
      case ExtractedExpr.EUnit => "()"
      case ExtractedExpr.EUnreachable(reason) =>
        s"""throw new AssertionError("Proof Samurai unreachable: ${reason.replace("\"", "'")}")"""
      case ExtractedExpr.EVar(name) =>
        safeIdent(name)
      case ExtractedExpr.EConst(name, typeArgs) =>
        val tStr = if (typeArgs.isEmpty) "" else s"[${typeArgs.map(emitType).mkString(", ")}]"
        s"${safeIdent(name)}$tStr"

      case ExtractedExpr.ECtor(indName, ctorName, typeArgs, args) =>
        val tStr = if (typeArgs.isEmpty) "" else s"[${typeArgs.map(emitType).mkString(", ")}]"
        if (recordNames.contains(indName)) {
          s"${safeIdent(indName)}$tStr(${args.map(emitExpr(_, defArities, recordNames, genericEnumNames, indent)).mkString(", ")})"
        } else if (args.isEmpty) {
          if (genericEnumNames.contains(indName)) s"${safeIdent(indName)}.${safeIdent(ctorName)}$tStr()"
          else s"${safeIdent(indName)}.${safeIdent(ctorName)}"
        } else {
          s"${safeIdent(indName)}.${safeIdent(ctorName)}$tStr(${args.map(emitExpr(_, defArities, recordNames, genericEnumNames, indent)).mkString(", ")})"
        }

      case ExtractedExpr.ELam(paramName, paramType, body) =>
        s"((${safeIdent(paramName)}: ${emitType(paramType)}) => ${emitExpr(body, defArities, recordNames, genericEnumNames, indent)})"

      case app @ ExtractedExpr.EApp(_, _) =>
        val (head, args) = collectApps(app)
        head match {
          case ExtractedExpr.EConst(fnName, typeArgs) if defArities.get(fnName).contains(args.length) =>
            val tStr = if (typeArgs.isEmpty) "" else s"[${typeArgs.map(emitType).mkString(", ")}]"
            val aStr = args.map(emitExpr(_, defArities, recordNames, genericEnumNames, indent)).mkString(", ")
            s"${safeIdent(fnName)}$tStr($aStr)"
          case ExtractedExpr.EConst(fnName, typeArgs) if defArities.get(fnName).exists(a => a > 0 && args.length > a) =>
            val arity = defArities(fnName)
            val (directArgs, extraArgs) = args.splitAt(arity)
            val tStr = if (typeArgs.isEmpty) "" else s"[${typeArgs.map(emitType).mkString(", ")}]"
            val base = s"${safeIdent(fnName)}$tStr(${directArgs.map(emitExpr(_, defArities, recordNames, genericEnumNames, indent)).mkString(", ")})"
            extraArgs.foldLeft(base)((acc, a) => s"$acc(${emitExpr(a, defArities, recordNames, genericEnumNames, indent)})")
          case _ =>
            val base = emitExpr(head, defArities, recordNames, genericEnumNames, indent)
            args.foldLeft(base)((acc, a) => s"$acc(${emitExpr(a, defArities, recordNames, genericEnumNames, indent)})")
        }

      case ExtractedExpr.ELet(name, value, body) =>
        val vStr = emitExpr(value, defArities, recordNames, genericEnumNames, indent + 2)
        val bStr = emitExpr(body, defArities, recordNames, genericEnumNames, indent + 2)
        s"{\n$pad  val ${safeIdent(name)} = $vStr\n$pad  $bStr\n$pad}"

      case ExtractedExpr.EMatch(indName, scrutinee, branches) =>
        val sStr = emitExpr(scrutinee, defArities, recordNames, genericEnumNames, indent)
        val sb = new StringBuilder
        sb.append(s"($sStr) match {\n")
        for ((ctorName, fieldNames, body) <- branches) {
          val actualPat =
            if (recordNames.contains(indName)) {
              s"${safeIdent(indName)}(${fieldNames.map(safeIdent).mkString(", ")})"
            } else if (fieldNames.isEmpty) {
              if (genericEnumNames.contains(indName)) s"${safeIdent(indName)}.${safeIdent(ctorName)}()"
              else s"${safeIdent(indName)}.${safeIdent(ctorName)}"
            } else {
              s"${safeIdent(indName)}.${safeIdent(ctorName)}(${fieldNames.map(safeIdent).mkString(", ")})"
            }
          val bStr = emitExpr(body, defArities, recordNames, genericEnumNames, indent + 4)
          sb.append(s"$pad  case $actualPat =>\n$pad    $bStr\n")
        }
        sb.append(s"$pad}")
        sb.toString
    }
  }
}
