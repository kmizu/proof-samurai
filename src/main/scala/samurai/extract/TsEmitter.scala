package samurai.extract

/**
 * Emits clean, standalone TypeScript (ES module with discriminated unions)
 * from an erased `ExtractedModule`.
 */
object TsEmitter {

  private def safeIdent(name: String): String =
    name.replace('\'', '_')

  def emit(module: ExtractedModule): String = {
    val sb = new StringBuilder
    sb.append("// ==========================================================================\n")
    sb.append("// Generated by Proof Samurai Code Extraction (Target: TypeScript)\n")
    sb.append(s"// Verified theorems (erased): ${module.manifest.verifiedTheorems.size}\n")
    sb.append(s"// Erased propositions:        ${module.manifest.erasedPropositions.size}\n")
    sb.append(s"// Axiom-free verification:    ${module.manifest.isAxiomFree}\n")
    sb.append("// ==========================================================================\n\n")

    for (data <- module.dataDecls) {
      emitDataDecl(sb, data)
      sb.append("\n")
    }

    val defArities = module.defDecls.map(d => d.name -> d.valueParams.length).toMap
    for (fn <- module.defDecls) {
      emitDefDecl(sb, fn, defArities)
      sb.append("\n")
    }

    sb.toString
  }

  private def emitDataDecl(sb: StringBuilder, data: ExtractedDataDecl): Unit = {
    val tParams =
      if (data.typeParams.isEmpty) ""
      else s"<${data.typeParams.map(safeIdent).mkString(", ")}>"
    val variants = data.constructors.map { ctor =>
      val fields = (s"""readonly tag: "${ctor.name}"""" :: ctor.fields.map { case (n, t) =>
        s"readonly ${safeIdent(n)}: ${emitType(t)}"
      }).mkString("; ")
      s"{ $fields }"
    }
    sb.append(s"export type ${safeIdent(data.name)}$tParams =\n  | ${variants.mkString("\n  | ")};\n")

    // Emit constructor helper functions
    sb.append(s"export const ${safeIdent(data.name)} = {\n")
    for (ctor <- data.constructors) {
      val args = ctor.fields.map { case (n, t) => s"${safeIdent(n)}: ${emitType(t)}" }.mkString(", ")
      val fieldAssigns = (s"""tag: "${ctor.name}" as const""" :: ctor.fields.map { case (n, _) => safeIdent(n) }).mkString(", ")
      sb.append(s"  ${safeIdent(ctor.name)}: $tParams($args): ${safeIdent(data.name)}$tParams => ({ $fieldAssigns }),\n")
    }
    sb.append("};\n")
  }

  private def emitDefDecl(sb: StringBuilder, fn: ExtractedDefDecl, defArities: Map[String, Int]): Unit = {
    val tParams =
      if (fn.typeParams.isEmpty) ""
      else s"<${fn.typeParams.map(safeIdent).mkString(", ")}>"
    val vParams = fn.valueParams.map { case (n, t) => s"${safeIdent(n)}: ${emitType(t)}" }.mkString(", ")
    sb.append(s"export function ${safeIdent(fn.name)}$tParams($vParams): ${emitType(fn.returnType)} {\n")
    sb.append(s"  return ${emitExpr(fn.body, defArities, indent = 2)};\n")
    sb.append("}\n")
  }

  private def emitType(ty: ExtractedType): String = ty match {
    case ExtractedType.TUnit          => "void"
    case ExtractedType.TVar(name)     => safeIdent(name)
    case ExtractedType.TAny           => "unknown"
    case ExtractedType.TInd(name, Nil) => safeIdent(name)
    case ExtractedType.TInd(name, args) => s"${safeIdent(name)}<${args.map(emitType).mkString(", ")}>"
    case ExtractedType.TFun(dom, cod) => s"((arg: ${emitType(dom)}) => ${emitType(cod)})"
  }

  private def collectApps(expr: ExtractedExpr): (ExtractedExpr, List[ExtractedExpr]) = {
    def loop(cur: ExtractedExpr, acc: List[ExtractedExpr]): (ExtractedExpr, List[ExtractedExpr]) = cur match {
      case ExtractedExpr.EApp(fn, arg) => loop(fn, arg :: acc)
      case other                       => (other, acc)
    }
    loop(expr, Nil)
  }

  private def emitExpr(expr: ExtractedExpr, defArities: Map[String, Int], indent: Int): String = {
    val pad = " " * indent
    expr match {
      case ExtractedExpr.EUnit => "undefined"
      case ExtractedExpr.EUnreachable(reason) =>
        s"""(() => { throw new Error("Proof Samurai unreachable: ${reason.replace("\"", "'")}"); })()"""
      case ExtractedExpr.EVar(name) => safeIdent(name)
      case ExtractedExpr.EConst(name, _) => safeIdent(name)
      case ExtractedExpr.ECtor(indName, ctorName, _, args) =>
        s"${safeIdent(indName)}.${safeIdent(ctorName)}(${args.map(emitExpr(_, defArities, indent)).mkString(", ")})"
      case ExtractedExpr.ELam(paramName, paramType, body) =>
        s"((${safeIdent(paramName)}: ${emitType(paramType)}) => ${emitExpr(body, defArities, indent)})"
      case app @ ExtractedExpr.EApp(_, _) =>
        val (head, args) = collectApps(app)
        head match {
          case ExtractedExpr.EConst(fnName, _) if defArities.get(fnName).contains(args.length) =>
            s"${safeIdent(fnName)}(${args.map(emitExpr(_, defArities, indent)).mkString(", ")})"
          case _ =>
            val base = emitExpr(head, defArities, indent)
            args.foldLeft(base)((acc, a) => s"$acc(${emitExpr(a, defArities, indent)})")
        }
      case ExtractedExpr.ELet(name, value, body) =>
        s"(() => { const ${safeIdent(name)} = ${emitExpr(value, defArities, indent + 2)}; return ${emitExpr(body, defArities, indent + 2)}; })()"
      case ExtractedExpr.EMatch(_, scrutinee, branches) =>
        val sStr = emitExpr(scrutinee, defArities, indent)
        val sb = new StringBuilder
        sb.append(s"((_scrut) => {\n$pad  switch (_scrut.tag) {\n")
        for ((ctorName, fieldNames, body) <- branches) {
          sb.append(s"""$pad    case "$ctorName": {\n""")
          for (fName <- fieldNames if fName != "_") {
            sb.append(s"$pad      const ${safeIdent(fName)} = _scrut.${safeIdent(fName)};\n")
          }
          sb.append(s"$pad      return ${emitExpr(body, defArities, indent + 6)};\n")
          sb.append(s"$pad    }\n")
        }
        sb.append(s"$pad  }\n$pad})($sStr)")
        sb.toString
    }
  }
}
